// Command clips speaks Famyy's short cues ("Okay!", "Let me ask Fo!") in the
// brain's Cartesia voice and writes them into the firmware as 16 kHz samples,
// so the device can say them the instant they're needed, with no network wait.
// Run it again after changing the voice:
//
//	go run ./cmd/clips                 (writes ../firmware/femi/clips.h and clips.cpp)
package main

import (
	"bufio"
	"context"
	"encoding/binary"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
	"time"

	"femi/brain/cartesia"
)

// groups of interchangeable clips; the device picks one of each group in turn
var groups = []struct {
	name  string
	texts []string
}{
	{"ACK", []string{"Okay!", "Hmm, let me see.", "Got it!", "One sec.", "Let me think."}},
	{"FO_START", []string{"Let me ask Fo!", "I'll get Fo on it."}},
	{"FO_WAIT", []string{"Fo's still on it.", "Almost there."}},
	{"HELLO", []string{"Hi! I'm Fammy."}},
	{"OFFLINE", []string{"Sorry, I can't reach my brain right now."}},
}

const rate = 16000

func main() {
	log.SetFlags(0)
	brainDir, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	key := os.Getenv("CARTESIA_API_KEY")
	if key == "" {
		key = envFileValue(filepath.Join(brainDir, ".env"), "CARTESIA_API_KEY")
	}
	if key == "" {
		log.Fatal("CARTESIA_API_KEY not set (environment or brain/.env)")
	}
	out := filepath.Join(brainDir, "..", "firmware", "femi")
	voice := cartesia.New(key)

	var h, c strings.Builder
	h.WriteString("// Generated by brain/cmd/clips: do not edit. Famyy's short spoken cues, 16 kHz mono, in the brain's voice.\n")
	h.WriteString("#pragma once\n#include <Arduino.h>\n\n")
	h.WriteString("struct Clip { const int16_t *pcm; uint32_t n; const char *text; };\nextern const Clip CLIPS[];\n\n")
	c.WriteString("// Generated by brain/cmd/clips: do not edit.\n#include \"clips.h\"\n\n")
	var table strings.Builder
	n, total := 0, 0
	for _, g := range groups {
		fmt.Fprintf(&h, "const int CLIP_%s = %d, CLIP_%s_N = %d;\n", g.name, n, g.name, len(g.texts))
		for _, text := range g.texts {
			ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
			pcm, err := voice.Speak(ctx, text, rate)
			cancel()
			if err != nil {
				log.Fatalf("%q: %v", text, err)
			}
			s := trim(samples(pcm))
			total += len(s)
			fmt.Fprintf(&c, "static const int16_t clip%d[] = {  // %q\n", n, text)
			for i, v := range s {
				if i%16 == 0 {
					c.WriteString("  ")
				}
				fmt.Fprintf(&c, "%d,", v)
				if i%16 == 15 || i == len(s)-1 {
					c.WriteString("\n")
				}
			}
			c.WriteString("};\n")
			fmt.Fprintf(&table, "  {clip%d, %d, %q},\n", n, len(s), text)
			log.Printf("%-42q %.2f s", text, float64(len(s))/rate)
			n++
		}
	}
	fmt.Fprintf(&h, "const int CLIP_COUNT = %d;\n", n)
	c.WriteString("\nconst Clip CLIPS[] = {\n" + table.String() + "};\n")
	if err := os.WriteFile(filepath.Join(out, "clips.h"), []byte(h.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(out, "clips.cpp"), []byte(c.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d clips, %.1f s, %d KB of flash", n, float64(total)/rate, total*2/1024)
}

func samples(pcm []byte) []int16 {
	s := make([]int16, len(pcm)/2)
	for i := range s {
		s[i] = int16(binary.LittleEndian.Uint16(pcm[2*i:]))
	}
	return s
}

// trim cuts the quiet before and after the words (keeping a breath of it), and fades the ends so they don't click
func trim(s []int16) []int16 {
	const quiet, before, after, fade = 400, rate / 50, rate / 12, rate / 200
	first, last := -1, -1
	for i, v := range s {
		if v > quiet || v < -quiet {
			if first < 0 {
				first = i
			}
			last = i
		}
	}
	if first < 0 {
		return s
	}
	s = s[max(0, first-before):min(len(s), last+after)]
	out := append([]int16(nil), s...)
	for i := 0; i < fade && i < len(out); i++ {
		out[i] = int16(int(out[i]) * i / fade)
		out[len(out)-1-i] = int16(int(out[len(out)-1-i]) * i / fade)
	}
	return out
}

func envFileValue(path, key string) string {
	f, err := os.Open(path)
	if err != nil {
		return ""
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimPrefix(strings.TrimSpace(sc.Text()), "export ")
		if k, v, ok := strings.Cut(line, "="); ok && strings.TrimSpace(k) == key {
			return strings.Trim(strings.TrimSpace(v), `"'`)
		}
	}
	return ""
}
